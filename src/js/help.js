let helpReturn = null;
function openHelp(id){
  $('#helpBody').innerHTML = HELP.map(h => `<details class="help-sec" id="help-${h.id}"${h.id === id ? ' open' : ''}><summary>${h.title}</summary><div>${h.body}</div></details>`).join('');
  helpReturn = document.activeElement;
  $('#helpWrap').hidden = false;
  document.body.classList.add('noscroll');
  const sec = $('#help-' + id) || $('#help-start');
  const panel = $('.helppanel');
  panel.focus();
  if (sec && id !== 'start') sec.scrollIntoView?.({ block:'start' });
}
function closeHelp(){
  $('#helpWrap').hidden = true;
  document.body.classList.remove('noscroll');
  if (helpReturn && helpReturn.focus) helpReturn.focus();
}
document.addEventListener('click', e => {
  const o = e.target.closest('[data-help]'); if (o){ e.preventDefault(); openHelp(o.dataset.help); return; }
  if (e.target.closest('[data-help-close]')) closeHelp();
});
document.addEventListener('keydown', e => {
  if ($('#helpWrap').hidden) return;
  if (e.key === 'Escape'){ closeHelp(); return; }
  if (e.key === 'Tab'){   // วนโฟกัสอยู่ในแผง
    const f = [...$('.helppanel').querySelectorAll('button, summary, a[href], input, select, textarea')].filter(x => !x.disabled && x.offsetParent !== null);
    if (!f.length) return;
    const first = f[0], last = f[f.length - 1];
    if (e.shiftKey && (document.activeElement === first || document.activeElement === $('.helppanel'))){ e.preventDefault(); last.focus(); }
    else if (!e.shiftKey && document.activeElement === last){ e.preventDefault(); first.focus(); }
  }
});
